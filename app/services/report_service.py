"""Structured research reports built from a completed research turn's evidence."""

from __future__ import annotations

from app.core.exceptions import LLMNotConfiguredError, NotFoundError, ValidationFailedError
from app.llm.research_llm import ResearchLLM
from app.persistence.database import Database
from app.persistence.models import Report
from app.persistence.repositories import ConversationRepository, ReportRepository
from app.schemas.reports import ReportContent, ReportFindingOut, ReportResponse
from app.schemas.research import AnswerClaim, Citation, EvidencePassage
from app.utils.citations import (
    best_excerpt,
    format_source,
    normalize_label,
)

_LABEL_IN_TEXT = r"\[?S\d+\]?"


def _valid_labels(raw: list[str], known: set[str]) -> list[str]:
    labels: list[str] = []
    for item in raw:
        label = normalize_label(item)
        if label in known and label not in labels:
            labels.append(label)
    return labels


def render_markdown(content: ReportContent) -> str:
    def bullets(items: list[str], empty: str) -> str:
        return "\n".join(f"- {item}" for item in items) if items else f"_{empty}_"

    def marks(labels: list[str]) -> str:
        return "".join(f" [{label}]" for label in labels)

    supported = [f for f in content.key_findings if f.kind == "supported_finding"]
    interpretations = [f for f in content.key_findings if f.kind == "interpretation"]
    lines = [
        f"# {content.title}",
        "",
        f"**Research question:** {content.research_question}",
        "",
        "## Executive summary",
        "",
        content.executive_summary,
        "",
        "## Key findings (supported by sources)",
        "",
        bullets([f.statement + marks(f.citations) for f in supported], "No supported findings."),
        "",
        "## Interpretations",
        "",
        bullets(
            [f.statement + marks(f.citations) for f in interpretations],
            "No interpretations beyond the sources.",
        ),
        "",
        "## Agreement between sources",
        "",
        bullets(content.agreements, "None identified in the evidence."),
        "",
        "## Disagreement between sources",
        "",
        bullets(content.disagreements, "None identified in the evidence."),
        "",
        "## Limitations and missing evidence",
        "",
        bullets(content.limitations, "None recorded."),
        "",
        "## Open questions",
        "",
        bullets(content.open_questions, "None."),
        "",
        "## Conclusion",
        "",
        content.conclusion,
        "",
        "## Evidence and citations",
        "",
    ]
    if content.sources:
        for source in content.sources:
            lines.append(f"- **[{source.source_id}]** {format_source(source)} — “{source.excerpt}”")
    else:
        lines.append("_No sources._")
    lines += [
        "",
        "---",
        "_Generated by ResearchFlow AI from uploaded documents only; no web research was "
        "performed. Verify important findings against the original sources._",
    ]
    return "\n".join(lines) + "\n"


class ReportService:
    def __init__(self, database: Database, llm: ResearchLLM) -> None:
        self.database = database
        self.llm = llm

    def create(self, turn_id: str) -> ReportResponse:
        with self.database.session() as session:
            turn = ConversationRepository(session).get_turn(turn_id)
            if turn is None:
                raise NotFoundError("Research turn not found.")
            if not turn.evidence:
                raise ValidationFailedError(
                    "This research turn has no retrieved evidence to build a report from."
                )
            question, answer = turn.question, turn.answer
            conversation_id = turn.conversation_id
            evidence = [EvidencePassage.model_validate(e) for e in turn.evidence]
            claims = [AnswerClaim.model_validate(c) for c in turn.claims or []]
            turn_limitations = list(turn.limitations or [])
        if not self.llm.configured:
            raise LLMNotConfiguredError()

        draft = self.llm.write_report(question, answer, evidence)
        by_label = {p.source_id: p for p in evidence}
        known = set(by_label)

        findings: list[ReportFindingOut] = []
        dropped = 0
        for finding in draft.key_findings:
            labels = _valid_labels(finding.source_ids, known)
            if finding.kind == "supported_finding" and not labels:
                dropped += 1  # a "supported" finding without verifiable sources is not kept
                continue
            findings.append(
                ReportFindingOut(statement=finding.statement, kind=finding.kind, citations=labels)
            )
        limitations = list(dict.fromkeys([*draft.limitations, *turn_limitations]))
        if dropped:
            limitations.append(
                f"{dropped} proposed finding(s) were removed because their sources could not "
                "be verified."
            )

        used = {label for f in findings for label in f.citations}
        used |= {label for c in claims if c.supported for label in c.citations}
        sources = [
            Citation(
                source_id=p.source_id,
                chunk_id=p.chunk_id,
                document_id=p.document_id,
                document_name=p.document_name,
                page=p.page,
                excerpt=best_excerpt(p.text, question),
            )
            for p in evidence
            if p.source_id in used
        ]
        content = ReportContent(
            title=draft.title.strip() or f"Research report: {question[:80]}",
            research_question=question,
            executive_summary=draft.executive_summary,
            key_findings=findings,
            agreements=draft.agreements,
            disagreements=draft.disagreements,
            limitations=limitations,
            open_questions=draft.open_questions,
            conclusion=draft.conclusion,
            sources=sources,
        )
        markdown = render_markdown(content)
        with self.database.session() as session:
            report = ReportRepository(session).add(
                Report(
                    turn_id=turn_id,
                    conversation_id=conversation_id,
                    title=content.title[:300],
                    content=content.model_dump(),
                    markdown=markdown,
                )
            )
            return self._to_response(report)

    def get(self, report_id: str) -> ReportResponse:
        with self.database.session() as session:
            report = ReportRepository(session).get(report_id)
            if report is None:
                raise NotFoundError("Report not found.")
            return self._to_response(report)

    def list_for_conversation(self, conversation_id: str) -> list[ReportResponse]:
        with self.database.session() as session:
            return [
                self._to_response(r)
                for r in ReportRepository(session).list_for_conversation(conversation_id)
            ]

    @staticmethod
    def _to_response(report: Report) -> ReportResponse:
        return ReportResponse(
            id=report.id,
            turn_id=report.turn_id,
            conversation_id=report.conversation_id,
            title=report.title,
            content=ReportContent.model_validate(report.content),
            markdown=report.markdown,
            created_at=report.created_at,
        )
